import { useState } from "react";
import { Loader2, Sparkles } from "lucide-react";
import { Button } from "@/components/ui/button";
import type { Deployment } from "@/hooks/useReadyDeployments";
import { INFERENCE_URL } from "@/lib/api";
import { getToken } from "@/lib/tokenStore";
import { generateWorkflow, type PlanSource } from "@/lib/workflow/generate";
import { NODE_KINDS } from "@/lib/workflow/nodeKinds";
import type { Workflow } from "@/lib/workflow/types";
import { cn } from "@/lib/utils";

const inputClass =
  "w-full rounded-md border bg-background px-2 py-1.5 text-xs outline-none focus:ring-1 focus:ring-ember-500";

// The planner call goes through the LLM node itself so it shares the sandbox auth and reasoning stripping.
function complete(model: string) {
  return async (system: string, user: string) => {
    const out = await NODE_KINDS.llm.run(
      { type: "text", text: user },
      { id: "planner", kind: "llm", position: { x: 0, y: 0 }, config: { model, systemPrompt: system } },
      { baseUrl: INFERENCE_URL, token: getToken(), fetch: window.fetch.bind(window), inputs: {} },
    );
    return out.type === "text" ? out.text : "";
  };
}

export function DescribeWorkflow({
  deployments,
  onGenerated,
}: {
  deployments: Deployment[];
  onGenerated: (workflow: Workflow) => void;
}) {
  const models = deployments.filter((d) => d.model_type === "inference" && d.modelName !== "-").map((d) => d.modelName);
  const [description, setDescription] = useState("");
  const [picked, setPicked] = useState("");
  const [busy, setBusy] = useState(false);
  const [source, setSource] = useState<PlanSource | null>(null);
  const model = models.includes(picked) ? picked : models[0];

  const submit = async () => {
    if (!description.trim() || busy) return;
    setBusy(true);
    try {
      const result = await generateWorkflow(description, model, model ? complete(model) : async () => "");
      setSource(result.source);
      onGenerated(result.workflow);
    } finally {
      setBusy(false);
    }
  };

  return (
    <section className="space-y-2">
      <h3 className="text-xs font-medium uppercase text-muted-foreground">Describe a workflow</h3>
      <textarea
        rows={3}
        value={description}
        onChange={(e) => setDescription(e.target.value)}
        onKeyDown={(e) => {
          if (e.key === "Enter" && (e.metaKey || e.ctrlKey)) void submit();
        }}
        placeholder="A voice assistant that answers questions and talks back"
        aria-label="Describe a workflow"
        className={cn(inputClass, "resize-y")}
      />
      <select value={model ?? ""} onChange={(e) => setPicked(e.target.value)} aria-label="Planner model" className={inputClass}>
        {models.length === 0 && <option value="">No inference deployments</option>}
        {models.map((m) => (
          <option key={m} value={m}>
            {m}
          </option>
        ))}
      </select>
      <Button size="sm" className="w-full" onClick={() => void submit()} disabled={busy || !description.trim()}>
        {busy ? <Loader2 className="mr-1.5 h-4 w-4 animate-spin" /> : <Sparkles className="mr-1.5 h-4 w-4" />}
        Generate
      </Button>
      {source && (
        <p
          className="line-clamp-3 text-[11px] text-muted-foreground"
          data-testid="plan-source"
          title={source.kind === "fallback" ? source.reason : undefined}
        >
          {source.kind === "model" ? (
            <>
              Generated by <span className="font-mono text-foreground">{source.model}</span>
            </>
          ) : (
            <>
              <span className="text-foreground">Fallback planner</span>: {source.reason}
            </>
          )}
        </p>
      )}
    </section>
  );
}
